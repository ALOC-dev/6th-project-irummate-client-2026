export function botReply(text: string): string {
  if (/마감|신청|기한/.test(text)) return '2학기 룸메이트 신청은 10월 6일 23:59까지예요. 매칭이 성사되면 신청서에 자동으로 등록돼요.';
  if (/매칭|추천|궁합/.test(text)) return '매일 자정에 생활 패턴이 잘 맞는 3명을 새로 추천해 드려요. MY에서 설문을 수정하면 추천이 더 정확해져요.';
  if (/세탁|점검|시설|고장/.test(text)) return '시설 문의는 생활관 행정실 채팅으로 남겨 주세요. 평일 09:00–18:00에 답변해요.';
  return '아직 그 질문은 잘 모르겠어요. 생활관 행정실이나 운영팀 채팅으로 문의해 주세요.';
}
